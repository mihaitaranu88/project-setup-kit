function frontmatter(fields) {
  return `---\n${Object.entries(fields).map(([key, value]) => `${key}: ${value}`).join('\n')}\n---\n`;
}

function quoteYaml(value) {
  return `'${value.replace(/'/g, "''")}'`;
}

function regexGrader(pattern) {
  return frontmatter({ type: 'regex', pattern: quoteYaml(pattern), flags: 'i' });
}

export function graderMatches(grader, text) {
  const pattern = grader.match(/^pattern: '((?:[^']|'')*)'$/m)[1].replace(/''/g, "'");
  const flags = grader.match(/^flags: (\w+)$/m)?.[1] ?? '';
  const count = grader.match(/^match: count:(\d+)$/m)?.[1];
  if (count !== undefined) return (text.match(new RegExp(pattern, `${flags}g`)) ?? []).length === Number(count);
  return new RegExp(pattern, flags).test(text);
}

const NOTHING_WRITTEN = frontmatter({ type: 'file_exists', path: '"**/*"', exists: 'false' });
const SKILL_FIRED = frontmatter({ type: 'tool_used', tool: 'Skill', input_match: quoteYaml('"skill"\\s*:\\s*"(?:[\\w-]+:)?setup-kit"'), arm: 'with-only' });

function scaffold(fixture, extra = '') {
  return `#!/usr/bin/env bash\nset -euo pipefail\nbash "$(dirname "$0")/../lib/prepare.sh" ${fixture}\n${extra}`;
}

function caseYaml(name, tags) {
  return `schema_version: "1.1"\nname: ${name}\ntags: [${tags.join(', ')}]\ncontext:\n  scaffold_script: scaffold.sh\n`;
}

function detectionCase(fixture, expected) {
  const languages = [...new Set((expected.parts ?? []).map(part => part.language.toLowerCase()))];
  const skipped = expected.notApplicable ?? [];
  const graders = {
    'nothing-written': NOTHING_WRITTEN,
    mode: regexGrader(`"mode"\\s*:\\s*"${expected.mode ?? 'existing'}"`),
  };
  for (const language of languages) graders[`language-${language}`] = regexGrader(`"language"\\s*:\\s*"${language}"`);
  for (const key of HAS_KEYS) {
    if (expected.has && key in expected.has) graders[`has-${key}`] = regexGrader(`"${key}"\\s*:\\s*${expected.has[key]}`);
  }
  graders['parts-count'] = frontmatter({ type: 'regex', pattern: quoteYaml('"language"\\s*:'), match: `count:${(expected.parts ?? []).length}` });
  for (const id of skipped) graders[`skips-item-${id}`] = regexGrader(`"(?:notApplicable|alreadyConfigured)"\\s*:\\s*\\[[^\\]]*(?<![\\d])"?${id}"?(?![\\d])`);
  return {
    name: `detect-${fixture}`,
    files: {
      'case.yaml': caseYaml(`detect-${fixture}`, ['detection']),
      'scaffold.sh': scaffold(fixture, fixture === 'empty' ? 'rm -rf .git\n' : ''),
      'prompt.md': `${frontmatter({ max_turns: 40, timeout_seconds: 900, allowed_tools: ALLOWED_TOOLS })}\n${DETECTION_PROMPT}\n`,
      ...Object.fromEntries(Object.entries(graders).map(([name, content]) => [`graders/${name}.md`, content])),
    },
  };
}

