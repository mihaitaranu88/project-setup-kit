export function buildCases() {
  const detection = readdirSync(FIXTURES)
    .filter(name => existsSync(join(FIXTURES, name, 'expected.json')))
    .sort()
    .map(fixture => detectionCase(fixture, JSON.parse(readFileSync(join(FIXTURES, fixture, 'expected.json'), 'utf8'))));
  return [...detection, ...behaviorCases()];
}

function listFiles(dir, prefix = '') {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap(entry =>
    entry.isDirectory() ? listFiles(join(dir, entry.name), `${prefix}${entry.name}/`) : [`${prefix}${entry.name}`],
  );
}

export function findDrift() {
  const problems = [];
  for (const evalCase of buildCases()) {
    const dir = join(EVALS, evalCase.name);
    const expected = { ...evalCase.files, GENERATED: `${GENERATED_NOTE}\n` };
    for (const [file, content] of Object.entries(expected)) {
      const path = join(dir, file);
      if (!existsSync(path) || readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== content) problems.push(`${evalCase.name}/${file}`);
    }
    for (const file of listFiles(dir)) if (!(file in expected)) problems.push(`${evalCase.name}/${file} (not generated)`);
  }
  return problems;
}

function write() {
  for (const evalCase of buildCases()) {
    const dir = join(EVALS, evalCase.name);
    rmSync(dir, { recursive: true, force: true });
    for (const [file, content] of Object.entries({ ...evalCase.files, GENERATED: `${GENERATED_NOTE}\n` })) {
      mkdirSync(join(dir, file, '..'), { recursive: true });
      writeFileSync(join(dir, file), content, { mode: file.endsWith('.sh') ? 0o755 : 0o644 });
    }
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
  if (process.argv.includes('--check')) {
    const drift = findDrift();
    if (drift.length > 0) {
      process.stderr.write(`Eval cases are out of date (run npm run build-evals):\n${drift.map(file => `  ${file}`).join('\n')}\n`);
      process.exitCode = 1;
    }
  } else {
    write();
  }
}
